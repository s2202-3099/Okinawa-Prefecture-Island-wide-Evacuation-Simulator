import json
from pathlib import Path

E = []
n = 0
def L(who, text, sub=None, **cue):
    global n
    n += 1
    e = {'id': f'l{n:03d}', 'who': who, 'text': text}
    if sub: e['sub'] = sub
    if cue: e['cue'] = cue
    E.append(e)
def P(frames): E.append({'pause': frames})
T = lambda *a, **k: L('t', *a, **k)
Z = lambda *a, **k: L('z', *a, **k)

